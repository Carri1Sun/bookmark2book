function chapter(
  index: number,
  title: string,
  introduction: string,
  sections: { heading: string; text: string[] }[],
  takeaway: string,
): Chapter {
  return {
    id: `chapter-${index}`,
    title,
    introduction,
    sourceIds: [],
    sections: sections.map((section) => ({
      heading: section.heading,
      paragraphs: section.text.map((text) => ({ text, sourceIds: [] })),
    })),
    takeaway,
  };
}
function demo(
  id: string,
  title: string,
  subtitle: string,
  description: string,
  theme: string,
  palette: Palette,
  chapters: Chapter[],
): Book {
  return {
    id,
    title,
    subtitle,
    description,
    theme,
    palette,
    chapters,
    sources: [],
    readingMinutes: Math.max(2, Math.ceil(JSON.stringify(chapters).length / 500)),
    createdAt: '2026-09-11T00:00:00Z',
    isDemo: true,
  };
}
